#!/usr/bin/env node
// Generate content/known-labels.js from data/fingerprint/human-decisions.json.
// Emits a global __BIPU_KNOWN_LABELS__ keyed by lowercase handle.
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const decisions = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'fingerprint', 'human-decisions.json'), 'utf8')).decisions;
const accounts = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'fingerprint', 'live_bot_accounts.json'), 'utf8'));

const labels = {};
for (const [aid, d] of Object.entries(decisions)) {
  const handle = (accounts[aid] && accounts[aid].username) || d.handle || aid;
  labels[String(handle).toLowerCase()] = {
    behavioral: d.behavioral || 'skip',
    intent: d.intent || 'unclear',
    reason: d.reason || '',
  };
}

const out = '// GENERATED by scripts/gen-known-labels.js — do not edit by hand.\n' +
  '// Baked-in confirmed human-review labels (data/fingerprint/human-decisions.json).\n' +
  'globalThis.__BIPU_KNOWN_LABELS__ = ' + JSON.stringify(labels, null, 2) + ';\n';
fs.writeFileSync(path.join(ROOT, 'content', 'known-labels.js'), out);
console.log('wrote content/known-labels.js with', Object.keys(labels).length, 'handles');
