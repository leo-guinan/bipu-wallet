#!/usr/bin/env node
// Static consistency checks for the bot-indicator content script wiring.
// Verifies: manifest order, classifier presence, known-labels freshness, syntax.
const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');
const ROOT = __dirname;
let pass = 0, fail = 0;

function check(name, ok, detail) {
  if (ok) { pass++; console.log('PASS  ' + name); }
  else { fail++; console.log('FAIL  ' + name + '  ' + (detail || '')); }
}

// 1. manifest declares the 3 content scripts in the right order (known-labels, classifier, indicator)
const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, 'manifest.json'), 'utf8'));
const cs = manifest.content_scripts && manifest.content_scripts.find(c => (c.matches||[]).includes('https://x.com/*'));
const order = cs ? cs.js : [];
check('manifest declares x.com content script', !!cs, JSON.stringify(cs && cs.matches));
check('script order: known-labels -> classifier -> indicator',
  JSON.stringify(order) === JSON.stringify(['content/known-labels.js', 'lib/bot-fingerprint.js', 'content/bot-indicator.js']),
  JSON.stringify(order));
check('x.com + twitter.com host permission present',
  manifest.host_permissions.includes('https://x.com/*') && manifest.host_permissions.includes('https://twitter.com/*'));
check('downloads permission present (training export)',
  manifest.permissions.includes('downloads'));

// 2. known-labels file is generated (not stale): handles match human-decisions.json
const decisions = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'fingerprint', 'human-decisions.json'), 'utf8')).decisions;
const accounts = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'fingerprint', 'live_bot_accounts.json'), 'utf8'));
const expectedHandles = new Set();
for (const [aid, d] of Object.entries(decisions)) {
  expectedHandles.add((accounts[aid] && accounts[aid].username || d.handle || aid).toLowerCase());
}
const knownSrc = fs.readFileSync(path.join(ROOT, 'content', 'known-labels.js'), 'utf8');
check('known-labels.js contains GENERATED banner', knownSrc.includes('GENERATED by scripts/gen-known-labels.js'));
for (const h of expectedHandles) {
  check('known-labels has handle: ' + h, knownSrc.includes('"' + h + '"'));
}

// 3. classifier lib exports what the content script needs
const libSrc = fs.readFileSync(path.join(ROOT, 'lib', 'bot-fingerprint.js'), 'utf8');
check('classifier exposes BIPU_BOT_FINGERPRINT', libSrc.includes('BIPU_BOT_FINGERPRINT'));

// 4. content script requires the classifier and known-labels globals (guards them)
const csSrc = fs.readFileSync(path.join(ROOT, 'content', 'bot-indicator.js'), 'utf8');
check('indicator guards on classifier load', csSrc.includes('if (!fp || !fp.classify)'));
check('indicator reads known-labels global', csSrc.includes('globalThis.__BIPU_KNOWN_LABELS__'));
check('indicator idempotent guard', csSrc.includes('window.__BIPU_BOT_INDICATOR__'));

// 5. syntax of all three files
for (const f of ['content/known-labels.js', 'lib/bot-fingerprint.js', 'content/bot-indicator.js']) {
  try { execSync('node --check ' + f, { cwd: ROOT }); check('syntax: ' + f, true); }
  catch (e) { check('syntax: ' + f, false, e.message); }
}

console.log('\n' + pass + '/' + (pass + fail) + ' content-script checks passed');
process.exit(fail ? 1 : 0);
